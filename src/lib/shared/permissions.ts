export type AdminRole = 'SUPER_ADMIN' | 'OPERATIONS_ADMIN' | 'FINANCE_ADMIN' | 'VERIFICATION_ADMIN' | 'SUPPORT_ADMIN';

export type Permission =
  | 'DASHBOARD_VIEW' | 'OPERATIONS_VIEW' | 'NURSES_VERIFY' | 'NURSES_MANAGE' | 'CUSTOMERS_MANAGE'
  | 'BOOKINGS_VIEW' | 'BOOKINGS_MANAGE' | 'FINANCE_VIEW' | 'WITHDRAWALS_MANAGE' | 'COMPLAINTS_MANAGE'
  | 'SERVICES_MANAGE' | 'GOVERNORATES_MANAGE' | 'SETTINGS_MANAGE' | 'ADMINS_MANAGE' | 'AUDIT_VIEW';

const ALL: Permission[] = [
  'DASHBOARD_VIEW', 'OPERATIONS_VIEW', 'NURSES_VERIFY', 'NURSES_MANAGE', 'CUSTOMERS_MANAGE', 'BOOKINGS_VIEW',
  'BOOKINGS_MANAGE', 'FINANCE_VIEW', 'WITHDRAWALS_MANAGE', 'COMPLAINTS_MANAGE', 'SERVICES_MANAGE',
  'GOVERNORATES_MANAGE', 'SETTINGS_MANAGE', 'ADMINS_MANAGE', 'AUDIT_VIEW',
];

export const ROLE_PERMISSIONS: Record<AdminRole, Permission[]> = {
  SUPER_ADMIN: ALL,
  OPERATIONS_ADMIN: ['DASHBOARD_VIEW', 'OPERATIONS_VIEW', 'NURSES_MANAGE', 'CUSTOMERS_MANAGE', 'BOOKINGS_VIEW',
    'BOOKINGS_MANAGE', 'SERVICES_MANAGE', 'GOVERNORATES_MANAGE'],
  FINANCE_ADMIN: ['DASHBOARD_VIEW', 'FINANCE_VIEW', 'WITHDRAWALS_MANAGE', 'BOOKINGS_VIEW'],
  VERIFICATION_ADMIN: ['DASHBOARD_VIEW', 'NURSES_VERIFY', 'NURSES_MANAGE'],
  SUPPORT_ADMIN: ['DASHBOARD_VIEW', 'COMPLAINTS_MANAGE', 'CUSTOMERS_MANAGE', 'BOOKINGS_VIEW', 'OPERATIONS_VIEW'],
};

export function can(role: string | null | undefined, permission: Permission): boolean {
  if (!role) return false;
  return (ROLE_PERMISSIONS[role as AdminRole] ?? []).includes(permission);
}
